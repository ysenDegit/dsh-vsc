    function t(key, params) {
      var lang = state.language === 'en' ? 'en' : 'zh';
      var str = (I18N[lang] && I18N[lang][key]) || I18N.zh[key] || key;
      if (params) {
        for (var k in params) {
          str = str.split('{' + k + '}').join(params[k]);
        }
      }
      return str;
    }

